#pragma once

#include "m0/ports/DownloadExecution.hpp"

#include <QIODevice>
#include <QString>

#include <cstdint>
#include <functional>
#include <memory>

namespace music_player::m0 {

struct WindowsDownloadWorkspaceConfig final {
    QString staging_parent{};
    QString publish_parent{};
    std::uint64_t max_workspace_bytes{512ULL * 1024 * 1024};
};

// Worker-thread object. Parents are existing trusted configuration; page data never
// supplies paths or filenames. Only the fresh job child receives the private DACL.
// The two sinks share one disk budget. Returned partial paths are internal inputs
// for the trusted converter/validator and must never be imported as finished media.
class WindowsDownloadWorkspace final {
  public:
    explicit WindowsDownloadWorkspace(WindowsDownloadWorkspaceConfig config);
    ~WindowsDownloadWorkspace();
    WindowsDownloadWorkspace(const WindowsDownloadWorkspace&) = delete;
    WindowsDownloadWorkspace& operator=(const WindowsDownloadWorkspace&) = delete;

    [[nodiscard]] bool create();
    [[nodiscard]] QIODevice* inputSink() noexcept;
    [[nodiscard]] bool sealInput();
    [[nodiscard]] QString inputPath() const;
    [[nodiscard]] QIODevice* outputSink() noexcept;
    [[nodiscard]] bool sealOutput();
    [[nodiscard]] QString outputPath() const;

    // Generated by this object, exposed to trusted composition/tests only. The
    // path is not a publication acknowledgement and cannot be set by a caller.
    [[nodiscard]] QString plannedPublicationPath() const;
    [[nodiscard]] QString validateAndPublish(const std::function<bool(const QString&)>& validate_mp3);
    [[nodiscard]] bool cleanup() noexcept;
    [[nodiscard]] DownloadFailure error() const noexcept;

  private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

} // namespace music_player::m0
