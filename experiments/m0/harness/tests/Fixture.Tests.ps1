Test-Case 'The generated fixture is byte-identical across roots and matches the committed set' {
    $generator = Join-Path $RepositoryRoot 'scripts\m0\New-M0ShellFixture.ps1'
    $first = Join-Path $TestTempRoot 'generated-first'
    $second = Join-Path $TestTempRoot 'generated-second'
    & $generator -DestinationRoot $first | Out-Null
    & $generator -DestinationRoot $second | Out-Null

    $expectedFiles = Get-TestRelativeFiles -Root $fixtureRoot
    Assert-SequenceEqual -Actual (Get-TestRelativeFiles -Root $first) -Expected $expectedFiles
    Assert-SequenceEqual -Actual (Get-TestRelativeFiles -Root $second) -Expected $expectedFiles
    foreach ($relativePath in $expectedFiles) {
        $committedHash = (Get-FileHash -LiteralPath (Join-Path $fixtureRoot $relativePath) -Algorithm SHA256).Hash
        $firstHash = (Get-FileHash -LiteralPath (Join-Path $first $relativePath) -Algorithm SHA256).Hash
        $secondHash = (Get-FileHash -LiteralPath (Join-Path $second $relativePath) -Algorithm SHA256).Hash
        Assert-Equal -Actual $firstHash -Expected $committedHash "Generated bytes differ for $relativePath."
        Assert-Equal -Actual $secondHash -Expected $committedHash "Second generation differs for $relativePath."
    }
}

