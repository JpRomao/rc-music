function Get-TestRelativeFiles {
    param([Parameter(Mandatory)] [string] $Root)

    [string[]] $relativeFiles = @(Get-ChildItem -LiteralPath $Root -Recurse -File | ForEach-Object {
        [IO.Path]::GetRelativePath($Root, $_.FullName).Replace('\', '/')
    })
    [Array]::Sort($relativeFiles, [StringComparer]::Ordinal)
    return $relativeFiles
}

function Get-TestContrastRatio {
    param(
        [Parameter(Mandatory)] [string] $Foreground,
        [Parameter(Mandatory)] [string] $Background
    )

    function Get-Luminance([string] $Color) {
        $channels = for ($offset = 1; $offset -le 5; $offset += 2) {
            $value = [Convert]::ToInt32($Color.Substring($offset, 2), 16) / 255.0
            if ($value -le 0.04045) { $value / 12.92 } else { [Math]::Pow(($value + 0.055) / 1.055, 2.4) }
        }
        return (0.2126 * $channels[0]) + (0.7152 * $channels[1]) + (0.0722 * $channels[2])
    }

    $foregroundLuminance = Get-Luminance $Foreground
    $backgroundLuminance = Get-Luminance $Background
    return ([Math]::Max($foregroundLuminance, $backgroundLuminance) + 0.05) /
        ([Math]::Min($foregroundLuminance, $backgroundLuminance) + 0.05)
}

